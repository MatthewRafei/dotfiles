# Packs the Space Invaders sprites into invaders.frag: rewrites the block
# between its @sprites markers. Rows of '#'/'.', one float per row, bit x =
# pixel x from the left. Run: python3 invaders_sprites.py (then qsb, see the .frag)
import os, re
here = os.path.dirname(os.path.abspath(__file__))
S = {}
S['SQUID_A'] = ["...##...","..####..",".######.","##.##.##","########","..#..#..",".#.##.#.","#.#..#.#"]
S['SQUID_B'] = ["...##...","..####..",".######.","##.##.##","########",".#.##.#.","#......#",".#....#."]
S['CRAB_A'] = ["..#.....#..","...#...#...","..#######..",".##.###.##.","###########","#.#######.#","#.#.....#.#","...##.##..."]
S['CRAB_B'] = ["..#.....#..","#..#...#..#","#.#######.#","###.###.###","###########",".#########.","..#.....#..",".#.......#."]
S['OCTO_A'] = ["....####....",".##########.","############","###..##..###","############","...##..##...","..##.##.##..","##........##"]
S['OCTO_B'] = ["....####....",".##########.","############","###..##..###","############","..###..###..",".##..##..##.","..##....##.."]
S['BOOM'] = [".#..#...#..#.","..#..#.#..#..","...#.....#...","##.........##","...#.....#...","..#..#.#..#..",".#..#...#..#.","............."]
S['CANNON'] = ["......#......",".....###.....",".....###.....",".###########.","#############","#############","#############","#############"]
S['UFO'] = [".....######.....","...##########...","..############..",".##.##.##.##.##.","################","..###..##..###..","...#........#...","................"]
S['BOMB_A'] = [".#.","#..",".#.","..#",".#.","#..",".#.","..."]
S['BOMB_B'] = [".#.","..#",".#.","#..",".#.","..#",".#.","..."]
S['BUNKER'] = ["....##############....","...################...","..##################..",".####################.",
               "######################","######################","######################","######################",
               "######################","######################","######################","######################",
               "#######........#######","######..........######","#####............#####","#####............#####"]
# Clawd, from widgets/Clawd.qml's runs: 16 x 10
grid = [['.'] * 16 for _ in range(10)]
for x, y, w, h in [[2,0,12,2],[2,2,2,2],[5,2,6,2],[12,2,2,2],[0,4,16,2],[2,6,12,2],[3,8,1,2],[5,8,1,2],[10,8,1,2],[12,8,1,2]]:
    for yy in range(y, y + h):
        for xx in range(x, x + w): grid[yy][xx] = '#'
S['CLAWD'] = [''.join(r) for r in grid] + ['.' * 16, '.' * 16]

def row(r): return sum(1 << i for i, ch in enumerate(r) if ch == '#')
def vecs(name, rows):
    vals = [float(row(r)) for r in rows]
    while len(vals) % 4: vals.append(0.0)
    out = []
    for i in range(0, len(vals), 4):
        out.append(f"const vec4 {name}{i // 4} = vec4({', '.join(f'{v:.1f}' for v in vals[i:i + 4])});")
    return out
consts = []
for n, rows in S.items():
    assert len(set(map(len, rows))) == 1, n
    consts += vecs(n, rows)
path = os.path.join(here, 'invaders.frag')
src = open(path).read()
block = '// @sprites begin\n' + '\n'.join(consts) + '\n// @sprites end'
src, n = re.subn(r'// @sprites begin\n.*?// @sprites end', lambda m: block, src, flags=re.S)
assert n == 1, 'markers not found'
open(path, 'w').write(src)
print('packed', len(consts), 'vec4 constants into invaders.frag')
